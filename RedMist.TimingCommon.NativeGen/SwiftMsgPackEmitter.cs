using System.Text;

namespace RedMist.TimingCommon.NativeGen;

/// <summary>
/// Emits <c>RedMistMsgPack.swift</c>: a dependency-free MessagePack reader and an
/// <c>init(msgpack:)</c> for every model, reading the same array slots the C# formatters write.
/// Mirrors the Kotlin RedMistMsgPack: a missing or nil slot reads as the default, extra slots are
/// ignored, the .NET timestamp extension becomes a Date, and contractless types are maps.
/// </summary>
internal sealed class SwiftMsgPackEmitter(TypeCatalog catalog)
{
    public void Write(string directory)
    {
        Directory.CreateDirectory(directory);
        File.WriteAllText(Path.Combine(directory, "RedMistMsgPack.swift"), Naming.Lf(Build()));
    }

    private string Build()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> by RedMist.TimingCommon.NativeGen from RedMist.TimingCommon. Do not edit.");
        sb.AppendLine();
        sb.AppendLine("import Foundation");
        sb.AppendLine();
        sb.AppendLine(Runtime);

        foreach (var t in catalog.Classes)
        {
            sb.AppendLine($"extension {t.Name} {{");
            sb.AppendLine("    /// Reads the MessagePack the server writes for this type.");
            sb.AppendLine("    public init(msgpack value: MsgPackValue) {");
            if (t.Props.Count == 0)
            {
                sb.AppendLine("        self.init()");
            }
            else
            {
                sb.AppendLine(t.IsKeyed
                    ? "        let a = value.arrayValue ?? []"
                    : "        let m = value.stringKeyedMap");
                sb.AppendLine("        self.init(");
                var lines = t.Props.Select(p =>
                {
                    var member = Naming.Member(p.Name);
                    var slot = t.IsKeyed ? $"a.slot({p.Key})" : $"m[\"{p.MapKey}\"]?.nonNil";
                    var expr = Decode(Nullable.GetUnderlyingType(p.ClrType) ?? p.ClrType, "$0");
                    var def = SwiftDefault(p);
                    if (!p.IsNullable)
                        return $"            {member}: {slot}.map {{ {expr} }} ?? {def}";
                    if (p.DefaultValue != null && t.IsKeyed)
                        return $"            {member}: a.count <= {p.Key} ? {def} : {slot}.map {{ {expr} }}";
                    return $"            {member}: {slot}.map {{ {expr} }}";
                });
                sb.AppendLine(string.Join(",\n", lines));
                sb.AppendLine("        )");
            }
            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine();
        }

        sb.AppendLine("public enum RedMistMsgPack {");
        sb.AppendLine("    /// Unpacks one MessagePack value (a whole REST body or hub argument).");
        sb.AppendLine("    public static func unpack(_ data: Data) throws -> MsgPackValue {");
        sb.AppendLine("        var reader = MsgPackReader(data)");
        sb.AppendLine("        return try reader.read()");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// Decoder for each model by its C# name, for code that picks a type at runtime (tests, fixtures).");
        sb.AppendLine("    public static let decoders: [String: @Sendable (MsgPackValue) -> Any] = [");
        sb.AppendLine(string.Join(",\n", catalog.Classes.Select(t => $"        \"{t.Name}\": {{ {t.Name}(msgpack: $0) }}")));
        sb.AppendLine("    ]");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private string Decode(Type type, string v)
    {
        if (type == typeof(int) || type == typeof(short) || type == typeof(ushort) || type == typeof(byte) || type == typeof(sbyte)
            || type == typeof(uint) || type == typeof(long) || type == typeof(ulong)) return $"{v}.intValue";
        if (type == typeof(double) || type == typeof(float) || type == typeof(decimal)) return $"{v}.doubleValue";
        if (type == typeof(bool)) return $"{v}.boolValue";
        if (type == typeof(string)) return $"{v}.stringValue";
        if (type == typeof(DateTime)) return $"{v}.dateValue";
        if (type == typeof(TimeOnly)) return $"{v}.timeOnlyValue";
        if (type.IsEnum) return $"{catalog.Names[type]}(rawValue: {v}.intValue) ?? .{Naming.EnumCase(FallbackCase(type))}";
        if (KotlinEmitter.ElementType(type) is { } element)
            return $"({v}.arrayValue ?? []).map {{ e in {Decode(element, "e")} }}";
        if (KotlinEmitter.IsDictionary(type, out var key, out var value))
            return $"Dictionary(({v}.mapValue ?? []).map {{ p in ({Decode(key, "p.key")}, {Decode(value, "p.value")}) }}, uniquingKeysWith: {{ _, last in last }})";
        if (catalog.IsClass(type)) return $"{catalog.Names[type]}(msgpack: {v})";
        throw new NotSupportedException($"No Swift MessagePack decoding for {type}");
    }

    private static string FallbackCase(Type enumType)
    {
        foreach (var name in Enum.GetNames(enumType))
            if (Convert.ToInt64(Enum.Parse(enumType, name)) == 0) return name;
        return Enum.GetNames(enumType)[0];
    }

    // The same defaults the Swift model initializers use.
    private string SwiftDefault(PropModel p)
    {
        var emitter = new SwiftEmitter(catalog);
        return emitter.DefaultFor(p);
    }

    private const string Runtime = """
        /// One MessagePack value.
        public enum MsgPackValue: Sendable, Equatable {
            case `nil`
            case bool(Bool)
            case int(Int64)
            case uint(UInt64)
            case double(Double)
            case string(String)
            case binary(Data)
            case array([MsgPackValue])
            case map([MsgPackPair])
            case ext(Int8, Data)

            var nonNil: MsgPackValue? { if case .nil = self { return nil }; return self }
            var arrayValue: [MsgPackValue]? { if case .array(let a) = self { return a }; return nil }
            var mapValue: [MsgPackPair]? { if case .map(let m) = self { return m }; return nil }
            var stringKeyedMap: [String: MsgPackValue] {
                var result: [String: MsgPackValue] = [:]
                for pair in mapValue ?? [] { result[pair.key.stringValue] = pair.value }
                return result
            }

            var intValue: Int {
                switch self {
                case .int(let v): return Int(truncatingIfNeeded: v)
                case .uint(let v): return Int(truncatingIfNeeded: v)
                case .double(let v): return Int(exactly: v.rounded(.towardZero)) ?? 0
                default: return 0
                }
            }

            var doubleValue: Double {
                switch self {
                case .double(let v): return v
                case .int(let v): return Double(v)
                case .uint(let v): return Double(v)
                case .string(let s): return Double(s) ?? 0 // .NET decimal is written as a string
                default: return 0
                }
            }

            var boolValue: Bool { if case .bool(let b) = self { return b }; return false }

            var stringValue: String {
                switch self {
                case .string(let s): return s
                case .int(let v): return String(v)
                case .uint(let v): return String(v)
                default: return ""
                }
            }

            /// The MessagePack timestamp extension (type -1), as .NET DateTime is written.
            var dateValue: Date {
                guard case .ext(-1, let d) = self else { return RedMistJSON.dotNetMinDate }
                let b = [UInt8](d)
                func be(_ range: Range<Int>) -> UInt64 { b[range].reduce(0) { ($0 << 8) | UInt64($1) } }
                let seconds: Int64
                let nanos: UInt64
                switch b.count {
                case 4: seconds = Int64(be(0..<4)); nanos = 0
                case 8:
                    let v = be(0..<8)
                    nanos = v >> 34
                    seconds = Int64(v & 0x3_FFFF_FFFF)
                case 12:
                    nanos = be(0..<4)
                    seconds = Int64(bitPattern: be(4..<12))
                default: return RedMistJSON.dotNetMinDate
                }
                // DateTime.MinValue: kept exact, as the JSON path does.
                if seconds == -62_135_596_800 && nanos == 0 { return RedMistJSON.dotNetMinDate }
                // Whole milliseconds, as the JSON path keeps, built the same way.
                return RedMistJSON.dateFrom(seconds: seconds, milliseconds: Int(nanos / 1_000_000))
            }

            /// .NET TimeOnly is written as its tick count; returns the text System.Text.Json writes.
            var timeOnlyValue: String {
                if case .string(let s) = self { return s }
                let ticks = Int64(intValue)
                let total = ticks / 10_000_000
                let fraction = ticks % 10_000_000
                func two(_ n: Int64) -> String { n < 10 ? "0\(n)" : "\(n)" }
                let base = "\(two(total / 3600)):\(two((total / 60) % 60)):\(two(total % 60))"
                if fraction == 0 { return base }
                let digits = String(fraction)
                return base + "." + String(repeating: "0", count: 7 - digits.count) + digits
            }
        }

        public struct MsgPackPair: Sendable, Equatable {
            public let key: MsgPackValue
            public let value: MsgPackValue
        }

        extension Array where Element == MsgPackValue {
            /// A keyed slot: missing (an older sender) or nil reads as absent.
            func slot(_ index: Int) -> MsgPackValue? { index < count ? self[index].nonNil : nil }
        }

        public enum MsgPackError: Error { case truncated, invalidFormat(UInt8), invalidString }

        /// Reads MessagePack (https://github.com/msgpack/msgpack/blob/master/spec.md).
        public struct MsgPackReader {
            private let bytes: [UInt8]
            private var offset = 0

            public init(_ data: Data) { bytes = [UInt8](data) }

            public mutating func read() throws -> MsgPackValue {
                let b = try byte()
                switch b {
                case 0x00...0x7f: return .int(Int64(b))
                case 0x80...0x8f: return try readMap(Int(b & 0x0f))
                case 0x90...0x9f: return try readArray(Int(b & 0x0f))
                case 0xa0...0xbf: return try readString(Int(b & 0x1f))
                case 0xc0: return .nil
                case 0xc2: return .bool(false)
                case 0xc3: return .bool(true)
                case 0xc4: return .binary(Data(try take(Int(try uint(1)))))
                case 0xc5: return .binary(Data(try take(Int(try uint(2)))))
                case 0xc6: return .binary(Data(try take(Int(try uint(4)))))
                case 0xc7: return try readExt(Int(try uint(1)))
                case 0xc8: return try readExt(Int(try uint(2)))
                case 0xc9: return try readExt(Int(try uint(4)))
                case 0xca: return .double(Double(Float(bitPattern: UInt32(try uint(4)))))
                case 0xcb: return .double(Double(bitPattern: try uint(8)))
                case 0xcc: return .uint(try uint(1))
                case 0xcd: return .uint(try uint(2))
                case 0xce: return .uint(try uint(4))
                case 0xcf: return .uint(try uint(8))
                case 0xd0: return .int(Int64(Int8(truncatingIfNeeded: try uint(1))))
                case 0xd1: return .int(Int64(Int16(truncatingIfNeeded: try uint(2))))
                case 0xd2: return .int(Int64(Int32(truncatingIfNeeded: try uint(4))))
                case 0xd3: return .int(Int64(bitPattern: try uint(8)))
                case 0xd4: return try readExt(1)
                case 0xd5: return try readExt(2)
                case 0xd6: return try readExt(4)
                case 0xd7: return try readExt(8)
                case 0xd8: return try readExt(16)
                case 0xd9: return try readString(Int(try uint(1)))
                case 0xda: return try readString(Int(try uint(2)))
                case 0xdb: return try readString(Int(try uint(4)))
                case 0xdc: return try readArray(Int(try uint(2)))
                case 0xdd: return try readArray(Int(try uint(4)))
                case 0xde: return try readMap(Int(try uint(2)))
                case 0xdf: return try readMap(Int(try uint(4)))
                case 0xe0...0xff: return .int(Int64(Int8(bitPattern: b)))
                default: throw MsgPackError.invalidFormat(b)
                }
            }

            private mutating func byte() throws -> UInt8 {
                guard offset < bytes.count else { throw MsgPackError.truncated }
                defer { offset += 1 }
                return bytes[offset]
            }

            private mutating func take(_ n: Int) throws -> ArraySlice<UInt8> {
                guard n >= 0, offset + n <= bytes.count else { throw MsgPackError.truncated }
                defer { offset += n }
                return bytes[offset..<offset + n]
            }

            private mutating func uint(_ n: Int) throws -> UInt64 {
                try take(n).reduce(0) { ($0 << 8) | UInt64($1) }
            }

            private mutating func readString(_ n: Int) throws -> MsgPackValue {
                guard let s = String(bytes: try take(n), encoding: .utf8) else { throw MsgPackError.invalidString }
                return .string(s)
            }

            private mutating func readArray(_ n: Int) throws -> MsgPackValue {
                var items: [MsgPackValue] = []
                items.reserveCapacity(Swift.min(n, bytes.count - offset)) // a corrupt header must not allocate gigabytes
                for _ in 0..<n { items.append(try read()) }
                return .array(items)
            }

            private mutating func readMap(_ n: Int) throws -> MsgPackValue {
                var pairs: [MsgPackPair] = []
                pairs.reserveCapacity(Swift.min(n, bytes.count - offset))
                for _ in 0..<n { pairs.append(MsgPackPair(key: try read(), value: try read())) }
                return .map(pairs)
            }

            private mutating func readExt(_ n: Int) throws -> MsgPackValue {
                let type = Int8(bitPattern: try byte())
                return .ext(type, Data(try take(n)))
            }
        }

        """;
}
