using System.Globalization;
using System.Text;

namespace RedMist.TimingCommon.NativeGen;

/// <summary>
/// Emits the iOS side (<c>RedMistModels.swift</c>): Codable value types keyed by the same JSON
/// names the server writes, a configured JSONDecoder, and patch application. iOS starts on the
/// JSON hub protocol, so there are no MessagePack decoders here yet.
/// </summary>
internal sealed class SwiftEmitter(TypeCatalog catalog)
{
    public void Write(string directory)
    {
        Directory.CreateDirectory(directory);
        File.WriteAllText(Path.Combine(directory, "RedMistModels.swift"), Naming.Lf(Models()));
    }

    private string Models()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> by RedMist.TimingCommon.NativeGen from RedMist.TimingCommon. Do not edit.");
        sb.AppendLine();
        sb.AppendLine("import Foundation");
        sb.AppendLine();
        sb.AppendLine("""
            /// JSON coding that matches the server: .NET DateTime as ISO-8601, with or without fractional
            /// seconds, and treated as UTC when it carries no offset.
            public enum RedMistJSON {
                /// .NET DateTime.MinValue (0001-01-01T00:00:00Z), the value an unset C# DateTime member holds.
                public static let dotNetMinDate = Date(timeIntervalSince1970: -62_135_596_800)

                public static func decoder() -> JSONDecoder {
                    let decoder = JSONDecoder()
                    decoder.dateDecodingStrategy = .custom { d in
                        let text = try d.singleValueContainer().decode(String.self)
                        if let date = parseDotNetDate(text) { return date }
                        throw DecodingError.dataCorrupted(.init(codingPath: d.codingPath, debugDescription: "Unrecognized date \(text)"))
                    }
                    return decoder
                }

                public static func encoder() -> JSONEncoder {
                    let encoder = JSONEncoder()
                    encoder.dateEncodingStrategy = .custom { date, e in
                        var c = e.singleValueContainer()
                        // The formatter's Julian calendar would write MinValue as 0001-01-03.
                        try c.encode(date == dotNetMinDate ? "0001-01-01T00:00:00Z" : withFraction.string(from: date))
                    }
                    return encoder
                }

                public static func parseDotNetDate(_ text: String) -> Date? {
                    // Foundation switches to the Julian calendar before 1582, so DateTime.MinValue would land 2 days off.
                    if text.hasPrefix("0001-01-01T00:00:00") { return dotNetMinDate }
                    var value = text
                    let hasZone = value.hasSuffix("Z") || value.range(of: #"[+-]\d{2}:\d{2}$"#, options: .regularExpression) != nil
                    if !hasZone { value += "Z" }
                    // The fraction is cut to whole milliseconds and added to the whole-second date, so the
                    // result is the same Double the MessagePack timestamp path builds.
                    var milliseconds = 0
                    if let dot = value.firstIndex(of: ".") {
                        let digitsEnd = value[dot...].dropFirst().firstIndex(where: { !$0.isNumber }) ?? value.endIndex
                        let digits = String(value[value.index(after: dot)..<digitsEnd].prefix(3))
                        milliseconds = Int(digits.padding(toLength: 3, withPad: "0", startingAt: 0)) ?? 0
                        value.removeSubrange(dot..<digitsEnd)
                    }
                    guard let whole = plain.date(from: value) else { return nil }
                    return dateFrom(seconds: Int64(whole.timeIntervalSince1970), milliseconds: milliseconds)
                }

                /// The one way both decoders build a Date, so equal instants compare equal.
                static func dateFrom(seconds: Int64, milliseconds: Int) -> Date {
                    Date(timeIntervalSince1970: Double(seconds) + Double(milliseconds) / 1000)
                }

                // ISO8601DateFormatter is thread-safe for parsing once configured.
                nonisolated(unsafe) private static let withFraction: ISO8601DateFormatter = {
                    let f = ISO8601DateFormatter()
                    f.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
                    return f
                }()

                nonisolated(unsafe) private static let plain: ISO8601DateFormatter = {
                    let f = ISO8601DateFormatter()
                    f.formatOptions = [.withInternetDateTime]
                    return f
                }()
            }

            """);

        foreach (var e in catalog.Enums)
            WriteEnum(sb, e);
        foreach (var t in catalog.Classes)
            WriteStruct(sb, t);
        foreach (var t in catalog.Classes.Where(c => c.PatchOf != null))
            WritePatch(sb, t);

        return sb.ToString();
    }

    private static void WriteEnum(StringBuilder sb, EnumModel e)
    {
        var fallback = e.Members.FirstOrDefault(m => m.Value == 0);
        if (fallback.Name == null) fallback = e.Members[0];

        sb.AppendLine($"/// Sent as its integer value, like the C# enum. Unknown values decode as `.{Naming.EnumCase(fallback.Name)}`.");
        sb.AppendLine($"public enum {e.Name}: Int, Codable, Sendable, CaseIterable {{");
        foreach (var (name, value) in e.Members)
            sb.AppendLine($"    case {Naming.EnumCase(name)} = {value}");
        sb.AppendLine();
        sb.AppendLine("    public init(from decoder: Decoder) throws {");
        sb.AppendLine("        let raw = try decoder.singleValueContainer().decode(Int.self)");
        sb.AppendLine($"        self = {e.Name}(rawValue: raw) ?? .{Naming.EnumCase(fallback.Name)}");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private void WriteStruct(StringBuilder sb, TypeModel t)
    {
        sb.AppendLine($"/// C# `{t.Clr.FullName}`.");
        sb.AppendLine($"public struct {t.Name}: Codable, Equatable, Sendable {{");
        foreach (var c in t.Consts)
            sb.AppendLine($"    public static let {Naming.Member(c.Name)}: {SType(c.ClrType, false)} = {Literal(c.Value)}");
        if (t.Consts.Count > 0) sb.AppendLine();

        foreach (var p in t.Props)
            sb.AppendLine($"    public var {Naming.Member(p.Name)}: {SType(p.ClrType, p.IsNullable)}");
        sb.AppendLine();

        // Memberwise init with the C# defaults, so callers and tests can build partial values.
        sb.AppendLine("    public init(");
        sb.AppendLine(string.Join(",\n", t.Props.Select(p => $"        {Naming.Member(p.Name)}: {SType(p.ClrType, p.IsNullable)} = {Default(p)}")));
        sb.AppendLine("    ) {");
        foreach (var p in t.Props)
            sb.AppendLine($"        self.{Naming.Member(p.Name)} = {Naming.Member(p.Name)}");
        sb.AppendLine("    }");
        sb.AppendLine();

        if (t.Props.Count > 0)
        {
            sb.AppendLine("    enum CodingKeys: String, CodingKey {");
            foreach (var p in t.Props)
                sb.AppendLine($"        case {Naming.Member(p.Name)} = \"{p.JsonKey}\"");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        // Missing keys fall back to the defaults, so an older or newer server still decodes.
        sb.AppendLine("    public init(from decoder: Decoder) throws {");
        if (t.Props.Count > 0)
        {
            sb.AppendLine("        let c = try decoder.container(keyedBy: CodingKeys.self)");
            foreach (var p in t.Props)
            {
                var m = Naming.Member(p.Name);
                // The element type to decode: decodeIfPresent adds the optional itself.
                var decodeType = SType(Nullable.GetUnderlyingType(p.ClrType) ?? p.ClrType, false);
                if (!p.IsNullable)
                    sb.AppendLine($"        {m} = try c.decodeIfPresent({decodeType}.self, forKey: .{m}) ?? {Default(p)}");
                else if (p.DefaultValue != null)
                    // null means nil; a key the sender never wrote keeps the C# initializer.
                    sb.AppendLine($"        {m} = try c.contains(.{m}) ? c.decodeIfPresent({decodeType}.self, forKey: .{m}) : {Default(p)}");
                else
                    sb.AppendLine($"        {m} = try c.decodeIfPresent({decodeType}.self, forKey: .{m})");
            }
        }
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void WritePatch(StringBuilder sb, TypeModel patch)
    {
        var target = patch.PatchOf!;
        var patchProps = patch.Props.Select(p => p.Name).ToHashSet();
        var shared = target.Props.Where(p => patchProps.Contains(p.Name)).ToList();

        sb.AppendLine($"extension {target.Name} {{");
        sb.AppendLine($"    /// Applies the non-nil fields of `patch`, like the C# {target.Name}Mapper.ApplyPatch.");
        sb.AppendLine($"    public mutating func apply(_ patch: {patch.Name}) {{");
        foreach (var p in shared)
        {
            var m = Naming.Member(p.Name);
            sb.AppendLine($"        if let v = patch.{m} {{ {m} = v }}");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    /// Every field as a patch, like the C# {target.Name}Mapper.CreatePatch from an empty state.");
        sb.AppendLine($"    public func toPatch() -> {patch.Name} {{");
        sb.AppendLine($"        {patch.Name}(");
        sb.AppendLine(string.Join(",\n", shared.Select(p => $"            {Naming.Member(p.Name)}: {Naming.Member(p.Name)}")));
        sb.AppendLine("        )");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private string SType(Type type, bool nullable)
    {
        var u = Nullable.GetUnderlyingType(type);
        if (u != null) return SType(u, false) + "?";
        var name = type switch
        {
            _ when type == typeof(int) || type == typeof(short) || type == typeof(ushort) || type == typeof(byte) || type == typeof(sbyte)
                || type == typeof(uint) || type == typeof(long) || type == typeof(ulong) => "Int",
            _ when type == typeof(double) || type == typeof(float) || type == typeof(decimal) => "Double",
            _ when type == typeof(bool) => "Bool",
            _ when type == typeof(string) || type == typeof(TimeOnly) => "String",
            _ when type == typeof(DateTime) => "Date",
            _ when type.IsEnum => catalog.Names[type],
            _ when KotlinEmitter.ElementType(type) is { } e => $"[{SType(e, false)}]",
            _ when KotlinEmitter.IsDictionary(type, out var k, out var v) => $"[{SType(k, false)}: {SType(v, false)}]",
            _ when catalog.IsClass(type) => catalog.Names[type],
            _ => throw new NotSupportedException($"No Swift type for {type}")
        };
        return nullable ? name + "?" : name;
    }

    internal string DefaultFor(PropModel p) => Default(p);

    private string Default(PropModel p)
    {
        if (p.IsNullable)
            return p.DefaultValue == null ? "nil" : Default(p with { IsNullable = false, ClrType = Nullable.GetUnderlyingType(p.ClrType) ?? p.ClrType });
        var t = p.ClrType;
        if (KotlinEmitter.ElementType(t) != null) return "[]";
        if (KotlinEmitter.IsDictionary(t, out _, out _)) return "[:]";
        if (t == typeof(DateTime)) return "RedMistJSON.dotNetMinDate";
        if (catalog.IsClass(t)) return $"{catalog.Names[t]}()";
        if (t.IsEnum)
        {
            var name = p.DefaultValue != null ? Enum.GetName(t, p.DefaultValue)! : Enum.GetNames(t)[0];
            return $".{Naming.EnumCase(name)}";
        }
        if (t == typeof(TimeOnly)) return "\"00:00:00\"";
        if (t == typeof(string)) return Literal(p.DefaultValue ?? "");
        return Literal(p.DefaultValue ?? Activator.CreateInstance(t));
    }

    private static string Literal(object? value) => value switch
    {
        null => "nil",
        string s => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"",
        bool b => b ? "true" : "false",
        double d => d.ToString("R", CultureInfo.InvariantCulture),
        float f => ((double)f).ToString("R", CultureInfo.InvariantCulture),
        decimal m => m.ToString(CultureInfo.InvariantCulture),
        _ => Convert.ToString(value, CultureInfo.InvariantCulture)!,
    };
}
